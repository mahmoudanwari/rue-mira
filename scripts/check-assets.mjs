// Verifies every image path referenced by the catalog and image map exists in public/
// with EXACT letter case (GitHub Pages runs on a case-sensitive filesystem), then
// writes docs/ASSET_STATUS.md. Never creates, renames, converts or moves images.
// Usage: npm run assets:check   (exit code 1 if anything is missing)
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const catalog = JSON.parse(readFileSync(join(root, "data/catalog.json"), "utf8"));
const map = JSON.parse(readFileSync(join(root, "data/image-map.json"), "utf8"));

/** @type {{ group: string; id: string; path: string }[]} */
const entries = [];
for (const p of catalog) p.images.forEach((img, i) => entries.push({ group: "Product images", id: `${p.id} ${i === 0 ? "main" : "detail"}`, path: img }));
for (const [k, v] of Object.entries(map.collections)) entries.push({ group: "Collection images", id: k, path: v });
for (const [k, v] of Object.entries(map.campaigns)) entries.push({ group: "Campaign, about & newsletter images", id: k, path: v });
for (const l of map.lookbook) entries.push({ group: "Lookbook images", id: l.id, path: l.image });

/** Case-sensitive existence check, segment by segment. */
function existsExact(relPath) {
  let dir = join(root, "public");
  for (const seg of relPath.split("/").filter(Boolean)) {
    if (!existsSync(dir)) return false;
    let names;
    try {
      names = readdirSync(dir);
    } catch {
      return false;
    }
    if (!names.includes(seg)) return false;
    dir = join(dir, seg);
  }
  return true;
}

const unique = new Map();
for (const e of entries) if (!unique.has(e.path)) unique.set(e.path, e);
const results = [...unique.values()].map((e) => ({ ...e, ok: existsExact(e.path) }));
const missing = results.filter((r) => !r.ok);

const groups = [...new Set(results.map((r) => r.group))];
let md = `# Asset status\n\nGenerated by \`npm run assets:check\` on ${new Date().toISOString().slice(0, 10)}.\n\n`;
md += `- Unique image paths referenced: **${results.length}** (expected 88)\n`;
md += `- Present (exact case): **${results.length - missing.length}**\n`;
md += `- Missing: **${missing.length}**\n\n`;
md +=
  "The check is case-sensitive on purpose: Windows ignores letter case, but GitHub Pages does not. " +
  "`72-home-featured-outfit.png` is intentionally used twice (New Arrivals collection tile and homepage), so it counts once.\n\n";
if (missing.length) {
  md += "## Missing files — how to resolve\n\n";
  md += "The site shows a neutral, non-photographic placeholder for these. Do not substitute other photos. Either place the supplied file at the exact path below, or fix the path in `data/catalog.json` / `data/image-map.json` if the file exists under a different name.\n\n";
  for (const m of missing) md += `- \`public${m.path}\` (${m.group} — ${m.id})\n`;
  md += "\n";
}
for (const g of groups) {
  md += `## ${g}\n\n| Status | ID | Path |\n|---|---|---|\n`;
  for (const r of results.filter((x) => x.group === g)) md += `| ${r.ok ? "✅ present" : "❌ missing"} | ${r.id} | \`${r.path}\` |\n`;
  md += "\n";
}
writeFileSync(join(root, "docs/ASSET_STATUS.md"), md);

console.log(`Referenced: ${results.length} · present: ${results.length - missing.length} · missing: ${missing.length}`);
for (const m of missing) console.log(`  MISSING public${m.path}`);
process.exit(missing.length ? 1 : 0);
